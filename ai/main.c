#include <stdio.h>
int main(void)
{
	float a, b, c;             // Параметры функции
	float StartX, EndX, dX;    // Начало, конец и шаг
	float x, F;               // Аргумент и значение функции
	long Ac, Bc, Cc;          // Целые части параметров
	long R;                   // Результат побитового выражения
	long i;                   // Номер шага

	printf("Введите:\n");

	// Вводим каждое число и проверяем правильность ввода
	printf("\ta = ");
	if (scanf("%f", &a) != 1)
	{
		printf("Ошибка: нужно ввести число.\n");
		return 1;
	}
	printf("\tb = ");
	if (scanf("%f", &b) != 1)
	{
		printf("Ошибка: нужно ввести число.\n");
		return 1;
	}
	printf("\tc = ");
	if (scanf("%f", &c) != 1)
	{
		printf("Ошибка: нужно ввести число.\n");
		return 1;
	}
	printf("\tX нач. = ");
	if (scanf("%f", &StartX) != 1)
	{
		printf("Ошибка: нужно ввести число.\n");
		return 1;
	}
	printf("\tX кон. = ");
	if (scanf("%f", &EndX) != 1)
	{
		printf("Ошибка: нужно ввести число.\n");
		return 1;
	}
	printf("\tdX = ");
	if (scanf("%f", &dX) != 1)
	{
		printf("Ошибка: нужно ввести число.\n");
		return 1;
	}
	// Проверяем шаг
	if (dX <= 0)
	{
		printf("Ошибка: шаг должен быть больше нуля.\n");
		return 1;
	}
	// Проверяем границы интервала
	if (StartX > EndX)
	{
		printf("Ошибка: начало интервала больше конца.\n");
		return 1;
	}
	// Получаем целые части, отбрасывая дробную часть
	Ac = (long)a;
	Bc = (long)b;
	Cc = (long)c;
	// Вычисляем Ац И (Вц ИЛИ Сц)
	R = Ac & (Bc | Cc);
	// Выводим заголовок таблицы
	printf("\n-----------------------------------------\n");
	printf("| %10s | %24s |\n", "x", "F");
	printf("-----------------------------------------\n");
	// Вычисляем x через номер шага
	for (i = 0; ; i++)
	{
		x = StartX + i * dX;
		// Завершаем цикл после выхода за конец интервала
		if (x > EndX)
			break;
		// Первая формула
		if (a < 0 && c != 0)
		{
			F = a * x * x + b * x + c;
		}
		// Вторая формула
		else if (a > 0 && b == 0)
		{
			// Проверяем знаменатель перед делением
			if (x == c)
			{
				printf("| %10.2f | %24s |\n", x, "F undefined");
				continue; // Выполняется i++, затем начинается следующий шаг
			}
			F = -a / (x - c);
		}
		// Третья формула
		else
		{
			F = a * (x + c);
		}
		// Выводим вещественный или целый результат
		if (R != 0)
		{
			printf("| %10.2f | %24.4f |\n", x, F);
		}
		else
		{
			// Отбрасываем дробную часть результата
			printf("| %10.2f | %24ld |\n", x, (long)F);
		}
	}
	printf("-----------------------------------------\n");
	return 0;
}
